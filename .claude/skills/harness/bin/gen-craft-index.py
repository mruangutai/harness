#!/usr/bin/env python3
"""Generate the per-seat `## Principles` index inside harness-craft/SKILL.md from the
leaves under harness-craft/references/.

Each leaf's frontmatter is the single source of truth for its trigger (`description`)
and who reads it (`seats`). The index is rendered between two HTML-comment markers in
SKILL.md; everything outside the markers is hand-written and untouched.

Usage:
    gen-craft-index.py            rewrite the index block in place
    gen-craft-index.py --check    exit 1 if the committed block differs from a fresh render
    gen-craft-index.py --stdout   print the rendered block, touch nothing
"""
import glob
import os
import re
import sys

import harness_boundary

_BIN_DIR = os.path.dirname(os.path.abspath(__file__))

SKILL_DIR = os.path.join(".claude", "skills", "harness-craft")
SKILL_PATH = os.path.join(SKILL_DIR, "SKILL.md")
LEAF_GLOB = os.path.join(SKILL_DIR, "references", "*.md")
LEAF_REL = "references"

BEGIN = "<!-- craft-index:begin — generated by bin/gen-craft-index.py; edit the leaves, not this block -->"
END = "<!-- craft-index:end -->"

SPECIALISTS = ("harness-frontend-dev", "harness-backend-dev", "harness-ai-dev",
               "harness-data-engineer", "harness-dev-ops")
SEATS = SPECIALISTS + ("harness-eng-lead", "harness-pm", "harness-code-reviewer", "harness-qa")
ALL_SPECIALISTS = "all five engineering specialists"
REQUIRED_KEYS = ("name", "title", "description", "seats")
FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n", re.S)


class LeafError(Exception):
    pass


def parse_frontmatter(path, text):
    match = FRONTMATTER_RE.match(text)
    if not match:
        raise LeafError(f"{path}: no frontmatter")
    fields = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            raise LeafError(f"{path}: malformed frontmatter line {line!r}")
        fields[key.strip()] = value.strip()
    missing = [k for k in REQUIRED_KEYS if k not in fields]
    if missing:
        raise LeafError(f"{path}: missing frontmatter keys {missing}")
    slug = os.path.splitext(os.path.basename(path))[0]
    if fields["name"] != slug:
        raise LeafError(f"{path}: name {fields['name']!r} != filename {slug!r}")
    desc = fields["description"]
    if not (desc.startswith('"') and desc.endswith('"')):
        raise LeafError(f"{path}: description must be double-quoted")
    desc = desc[1:-1]
    if not desc.startswith("Apply"):
        raise LeafError(f"{path}: description must start with 'Apply'")
    seats_raw = fields["seats"].strip("[]")
    seats = [s.strip() for s in seats_raw.split(",") if s.strip()]
    unknown = [s for s in seats if s not in SEATS]
    if unknown or not seats:
        raise LeafError(f"{path}: seats {seats} must be a non-empty subset of {list(SEATS)}")
    if seats != [s for s in SEATS if s in seats]:
        raise LeafError(f"{path}: seats must be in canonical order {list(SEATS)}")
    return {"slug": slug, "title": fields["title"], "description": desc, "seats": seats}


def load_leaves():
    leaves = []
    for path in sorted(glob.glob(LEAF_GLOB)):
        with open(path, encoding="utf-8") as fh:
            leaves.append(parse_frontmatter(path, fh.read()))
    if not leaves:
        raise LeafError(f"no leaves under {LEAF_GLOB}")
    return leaves


def trigger(description):
    """The 'Apply when …' sentence alone; the leaf carries the rule."""
    head, sep, _ = description.partition(". ")
    return head + ("." if sep else "")


def seat_label(seats):
    """Real agent names; the exact five-specialist set collapses to one phrase."""
    rest = [s for s in seats if s not in SPECIALISTS]
    if all(s in seats for s in SPECIALISTS):
        return ", ".join([ALL_SPECIALISTS] + [f"`{s}`" for s in rest])
    return ", ".join(f"`{s}`" for s in seats)


def render(leaves):
    lines = [BEGIN, ""]
    for leaf in leaves:
        seats = seat_label(leaf["seats"])
        lines.append(
            f"- **{leaf['title']}** (`{LEAF_REL}/{leaf['slug']}.md`) — {seats}. "
            f"{trigger(leaf['description'])}"
        )
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def split_skill(text):
    begin = text.find(BEGIN)
    end = text.find(END)
    if begin < 0 or end < 0 or end < begin:
        raise LeafError(f"{SKILL_PATH}: index markers missing or out of order")
    return text[:begin], text[begin:end + len(END)], text[end + len(END):]


def main(argv):
    mode = "write"
    if argv == ["--check"]:
        mode = "check"
    elif argv == ["--stdout"]:
        mode = "stdout"
    elif argv:
        print(__doc__, file=sys.stderr)
        return 2

    os.chdir(harness_boundary.resolve_root(_BIN_DIR))
    try:
        block = render(load_leaves())
        if mode == "stdout":
            sys.stdout.write(block + "\n")
            return 0
        with open(SKILL_PATH, encoding="utf-8") as fh:
            text = fh.read()
        head, current, tail = split_skill(text)
    except LeafError as err:
        print(f"gen-craft-index: {err}", file=sys.stderr)
        return 1

    if current == block:
        return 0
    if mode == "check":
        print(f"gen-craft-index: {SKILL_PATH} index block is stale; run gen-craft-index.py",
              file=sys.stderr)
        return 1
    with open(SKILL_PATH, "w", encoding="utf-8") as fh:
        fh.write(head + block + tail)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
